package transcoder

import (
	"encoding/xml"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func measuredManifestTrack(t *testing.T, dir, track string, sizes []int) {
	t.Helper()
	path := filepath.Join(dir, track)
	if err := os.MkdirAll(path, 0755); err != nil {
		t.Fatal(err)
	}
	var body strings.Builder
	body.WriteString("#EXTM3U\n#EXT-X-TARGETDURATION:6\n#EXT-X-MAP:URI=\"init.mp4?verify={$verify}\"\n")
	for i, size := range sizes {
		name := fmt.Sprintf("segment_%04d.m4s", i)
		if err := os.WriteFile(filepath.Join(path, name), make([]byte, size), 0644); err != nil {
			t.Fatal(err)
		}
		fmt.Fprintf(&body, "#EXTINF:6.000000,\n%s?verify={$verify}\n", name)
	}
	body.WriteString("#EXT-X-ENDLIST\n")
	if err := os.WriteFile(filepath.Join(path, "playlist.m3u8"), []byte(body.String()), 0644); err != nil {
		t.Fatal(err)
	}
	// Initialization bytes are excluded from the declarations by definition.
	if err := os.WriteFile(filepath.Join(path, "init.mp4"), make([]byte, 100_000), 0644); err != nil {
		t.Fatal(err)
	}
}

type measuredManifestDocument struct {
	MinBufferTime string `xml:"minBufferTime,attr"`
	Period        struct {
		Sets []struct {
			Type string `xml:"contentType,attr"`
			Reps []struct {
				ID        string `xml:"id,attr"`
				Bandwidth int64  `xml:"bandwidth,attr"`
				FrameRate string `xml:"frameRate,attr"`
			} `xml:"Representation"`
		} `xml:"AdaptationSet"`
	} `xml:"Period"`
}

func readMeasuredManifest(t *testing.T, dir string) (string, measuredManifestDocument) {
	t.Helper()
	body, err := os.ReadFile(filepath.Join(dir, "manifest.mpd"))
	if err != nil {
		t.Fatal(err)
	}
	var document measuredManifestDocument
	if err := xml.Unmarshal(body, &document); err != nil {
		t.Fatal(err)
	}
	return string(body), document
}

func TestManifestsDeclareMeasuredRatesWithOptionalAudio(t *testing.T) {
	for _, audio := range []bool{false, true} {
		t.Run(fmt.Sprintf("audio_%v", audio), func(t *testing.T) {
			dir := t.TempDir()
			measuredManifestTrack(t, dir, "video/test", []int{6000, 24000, 6000})
			if audio {
				measuredManifestTrack(t, dir, "audio/aac", []int{750, 750, 750})
			}
			// Targets are deliberately unrelated to the generated bytes.
			variant := Variant{Name: "test", Codecs: "avc1.64002A", Width: 1280, Height: 720, VideoBitrateKbps: 987654, FrameRate: 30, FrameRateNum: 60000, FrameRateDen: 1001}
			if err := WriteMasterPlaylist(dir, []Variant{variant}, "aac", 8765, audio); err != nil {
				t.Fatal(err)
			}
			if err := WriteDASHManifest(dir, []Variant{variant}, "aac", 8765, 48000, 18, audio); err != nil {
				t.Fatal(err)
			}
			masterBytes, err := os.ReadFile(filepath.Join(dir, "master.m3u8"))
			if err != nil {
				t.Fatal(err)
			}
			master := string(masterBytes)
			// Video: 36,000B / 18s = 16kb/s average; 24,000B / 6s =
			// 32kb/s HLS peak. The 2s DASH buffer gives 24kb/s for the burst.
			// Constant audio contributes 750B*8/6s = 1kb/s to both HLS rates.
			peak, average := 32000, 16000
			if audio {
				peak += 1000
				average += 1000
			}
			if !strings.Contains(master, fmt.Sprintf("BANDWIDTH=%d,AVERAGE-BANDWIDTH=%d,", peak, average)) {
				t.Fatalf("HLS does not declare independently calculated rates: %s", master)
			}
			for _, attribute := range []string{`#EXT-X-MEDIA:TYPE=AUDIO`, `AUDIO="audio"`, `,mp4a.40.2`} {
				if strings.Contains(master, attribute) != audio {
					t.Fatalf("audio=%v attribute %q: %s", audio, attribute, master)
				}
			}
			_, mpd := readMeasuredManifest(t, dir)
			if mpd.MinBufferTime != "PT2S" {
				t.Fatalf("DASH buffer=%q", mpd.MinBufferTime)
			}
			if got := mpd.Period.Sets[0].Reps[0]; got.Bandwidth != 24000 || got.FrameRate != "60000/1001" {
				t.Fatalf("video declaration=%#v", got)
			}
			if audio {
				if len(mpd.Period.Sets) != 2 || mpd.Period.Sets[1].Reps[0].Bandwidth != 1000 {
					t.Fatalf("audio declaration=%#v", mpd.Period.Sets)
				}
			} else if len(mpd.Period.Sets) != 1 {
				t.Fatalf("unexpected audio set: %#v", mpd.Period.Sets)
			}
		})
	}
}

func TestConstantArtifactRatesAndManifestRationalFrameRate(t *testing.T) {
	for _, tc := range []struct {
		name         string
		n, d, legacy int
		want         string
	}{
		{"fractional", 60000, 1001, 30, "60000/1001"}, {"reduced", 120000, 2002, 60, "60000/1001"}, {"low", 1, 5, 30, "1/5"}, {"legacy", 0, 0, 24, "24"}, {"unknown", 0, 0, 0, ""},
	} {
		t.Run(tc.name, func(t *testing.T) {
			dir := t.TempDir()
			measuredManifestTrack(t, dir, "video/test", []int{6000, 6000})
			v := Variant{Name: "test", Codecs: "avc1.64002A", VideoBitrateKbps: 999999, FrameRate: tc.legacy, FrameRateNum: tc.n, FrameRateDen: tc.d}
			if err := WriteMasterPlaylist(dir, []Variant{v}, "", 999, false); err != nil {
				t.Fatal(err)
			}
			if err := WriteDASHManifest(dir, []Variant{v}, "", 999, 0, 12, false); err != nil {
				t.Fatal(err)
			}
			body, mpd := readMeasuredManifest(t, dir)
			rep := mpd.Period.Sets[0].Reps[0]
			// Constant 6000-byte / 6-second segments are exactly 8000b/s for
			// average, peak, and the conservative DASH average floor.
			if rep.Bandwidth != 8000 || rep.FrameRate != tc.want {
				t.Fatalf("declaration=%#v want fps %q", rep, tc.want)
			}
			master, err := os.ReadFile(filepath.Join(dir, "master.m3u8"))
			if err != nil {
				t.Fatal(err)
			}
			if !strings.Contains(string(master), "BANDWIDTH=8000,AVERAGE-BANDWIDTH=8000,") {
				t.Fatalf("constant HLS declaration=%s", master)
			}
			if tc.want == "" && strings.Contains(body, "frameRate=") {
				t.Fatalf("unknown frame rate must be omitted: %s", body)
			}
		})
	}
}
